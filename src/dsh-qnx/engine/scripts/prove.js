#!/usr/bin/env node
'use strict';
// Produces the receipts document for the done-tests, against a RUNNING target
// (runner + gateway per standin/config.json, or the QNX QEMU guest later).
// Every number in the output is measured in this run; nothing is typed in.
//
//   node scripts/prove.js standin/config.json docs/receipts
//
// Sections: Phase 2 ladder · Phase 3 zero-packets (tcpdump witness) + engagement
// + chain · sandbox negative controls · Phase 4 checks · Phase 6 loop · token
// surface (cl100k_base proxy, if tiktoken is installed).
const fs = require('fs');
const path = require('path');
const { spawn, execFileSync, spawnSync } = require('child_process');
const { loadConfig } = require('../gateway/server');
const { McpClient, request } = require('../gateway/lib/mcp-client');
const { verifyChain } = require('../gateway/lib/audit');
const { workBoard } = require('../loop/smith');

const [cfgFile = 'standin/config.json', outDir = 'docs/receipts'] = process.argv.slice(2);
const cfg = loadConfig(cfgFile);
const st = cfg.state_dir;
const base = `http://${cfg.listen.host}:${cfg.listen.port}`;
const tok = (s) => fs.readFileSync(path.join(st, `seat-${s}.token`), 'utf8').trim();
const cli = (...a) => execFileSync(process.execPath, [path.join(__dirname, '..', 'gateway', 'cli.js'), ...a], { encoding: 'utf8' }).trim();
// The runner's spawn log is the target-side record of what ran: a local file on the stand-in, on the guest for QNX.
const ssh = cfg.target_ssh;
const spawnCount = () => {
  if (ssh) {
    const r = spawnSync('ssh', ['-i', path.resolve(path.dirname(path.resolve(cfgFile)), ssh.key), '-p', String(ssh.port), '-o', 'StrictHostKeyChecking=no', '-o', 'BatchMode=yes',
      `${ssh.user}@${ssh.host}`, `cat ${ssh.spawn_log} 2>/dev/null | wc -l`], { encoding: 'utf8' });
    return Number(String(r.stdout).trim()) || 0;
  }
  try { return fs.readFileSync(cfg.runner.spawn_log || path.join(st, 'spawn.log'), 'utf8').split('\n').filter(Boolean).length; } catch { return 0; }
};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const md = [];
const out = (s = '') => { md.push(s); console.log(s); };
const code = (s, lang = '') => out('```' + lang + '\n' + String(s).trim() + '\n```');

function witness(host) {
  // tcpdump on every interface for any packet to/from the target address.
  const p = spawn('tcpdump', ['-i', 'any', '-nn', '-l', '-U', 'host', host], { stdio: ['ignore', 'pipe', 'pipe'] });
  const lines = [];
  let ready;
  const readyP = new Promise((r) => (ready = r));
  p.stdout.setEncoding('utf8');
  p.stdout.on('data', (d) => lines.push(...d.split('\n').filter(Boolean)));
  p.stderr.setEncoding('utf8');
  p.stderr.on('data', (d) => { if (/listening on/.test(d)) ready(); });
  return { ready: Promise.race([readyP, sleep(3000)]), stop: async () => { await sleep(1200); p.kill('SIGINT'); await sleep(300); return lines; } };
}

(async () => {
  const runner = new McpClient(base, tok('runner'));
  const operator = new McpClient(base, tok('operator'));
  const state = (await operator.get('/api/state')).json;
  const t = state.target;
  const date = new Date().toISOString().slice(0, 10);
  out(`# Receipts — ${t.os} ${t.release} target "${t.hostname}" (${date})`);
  out();
  out(t.os === 'QNX'
    ? `Target: **QNX ${t.qnx_version || t.release}** on ${t.machine} (QEMU guest).`
    : `Target: **Linux stand-in** (${t.release}, ${t.machine}). This run proves the gateway, gate, runner, checks and loop on a POSIX stand-in before the QNX SDP is installed. **It is not a QNX run.** The same script re-runs unchanged against the QNX 8.0 QEMU guest at Phase 0.`);
  out();
  out(`Generated by \`node scripts/prove.js\` at ${new Date().toISOString()}. Every value below was measured in this run.`);
  out();

  // ---------- Phase 2 ladder ----------
  out('## Phase 2 — the ladder');
  out();
  const r401 = await request(base, null, 'POST', '/mcp', { jsonrpc: '2.0', id: 1, method: 'tools/list' });
  await runner.initialize();
  const tools = await runner.listTools();
  const s = await runner.search('open ports listening sockets', 4);
  const ex = await runner.execute('const n = await tools.netstat(["-an"]); const l = parse.listeners(n.stdout); return { listeners: l.length, sample: l.slice(0, 3), receipt: n.receipt };');
  out('| Rung | Result |');
  out('|---|---|');
  out(`| No token | HTTP ${r401.status} \`${r401.text.trim()}\` |`);
  out(`| \`tools/list\` | \`${JSON.stringify(tools.map((x) => x.name))}\` |`);
  out(`| \`search("open ports listening sockets")\` | top: ${s.matches.map((m) => `\`${m.name}\` (${m.class}${m.callable ? '' : ', off'})`).join(', ')} — catalog ${s.catalog_size} tools, ${s.visible_size} callable |`);
  out(`| \`execute\` → \`tools.netstat(["-an"])\` on the target | ok=${ex.ok}, ${ex.value.listeners} listeners parsed, receipt \`${ex.value.receipt.slice(0, 16)}…\` |`);
  out();

  // ---------- Phase 3 zero packets ----------
  out('## Phase 3 — out-of-scope call denied pre-spawn, zero packets');
  out();
  const victim = '192.0.2.77'; // TEST-NET-1, never a real host
  try { cli('engage', 'revoke', st, '--id', 'proof-lab'); } catch {}
  const prog = `const r = await tools.ping(["-c", "2", "-W", "1", "${victim}"]); return { exit: r.exit, stdout: r.stdout.split("\\n").slice(0, 2).join(" | "), receipt: r.receipt };`;
  const haveTcpdump = spawnSync('tcpdump', ['--version']).status === 0;
  let w = haveTcpdump ? witness(victim) : null;
  if (w) await w.ready;
  const sp0 = spawnCount();
  const denied = await runner.execute(prog);
  const sp1 = spawnCount();
  const deniedPackets = w ? await w.stop() : null;
  out(`**Call:** \`tools.ping(["-c","2","-W","1","${victim}"])\` with no engagement for ${victim}.`);
  out();
  out(`- Result: \`${denied.error.kind}/${denied.error.code}\` — ${denied.error.message}`);
  out(`- Target-side spawn log: ${sp0} → ${sp1} (**${sp1 - sp0} processes spawned**)`);
  out(`- Packet witness (\`tcpdump -i any -nn host ${victim}\`, running before and after the call): **${deniedPackets ? deniedPackets.length : 'n/a'} packets**`);
  out(`- Denial receipt: \`${denied.error.receipt}\``);
  out();
  cli('engage', 'add', st, '--id', 'proof-lab', '--target', '192.0.2.0/24', '--hours', '1', '--operator', 'prove.js');
  out(`Operator signs an engagement: \`cli.js engage add --id proof-lab --target 192.0.2.0/24\` (HMAC-SHA256 with the operator key; agent seats cannot mint one).`);
  out();
  w = haveTcpdump ? witness(victim) : null;
  if (w) await w.ready;
  const sp2 = spawnCount();
  const allowed = await runner.execute(prog, 20000);
  const sp3 = spawnCount();
  const allowedPackets = w ? await w.stop() : null;
  out(`**Identical call** after the engagement:`);
  out();
  out(`- Result: ok=${allowed.ok}, ping exit ${allowed.value && allowed.value.exit} (TEST-NET has no host; the packets still leave)`);
  out(`- Spawn log: ${sp2} → ${sp3} (**${sp3 - sp2} spawned**)`);
  out(`- Packet witness: **${allowedPackets ? allowedPackets.length : 'n/a'} packets** — positive control: the witness does see traffic when traffic exists`);
  if (allowedPackets && allowedPackets.length) code(allowedPackets.slice(0, 4).join('\n'));
  out(`- Allow receipt: \`${allowed.value && allowed.value.receipt}\``);
  out();
  cli('engage', 'revoke', st, '--id', 'proof-lab');
  const after = await runner.execute(prog);
  out(`Engagement revoked → identical call: \`${after.error && after.error.code}\` again.`);
  out();
  const chain = verifyChain(path.join(st, 'audit.log'));
  out(`Audit chain: **${chain.ok ? 'VERIFIED' : 'BROKEN'}**, ${chain.count} entries, head \`${chain.head}\`.`);
  out();
  const proof3 = { denied_spawned: sp1 - sp0, denied_packets: deniedPackets && deniedPackets.length, allowed_spawned: sp3 - sp2, allowed_packets: allowedPackets && allowedPackets.length };

  // ---------- sandbox ----------
  out('## Sandbox negative controls');
  out();
  const probes = [
    ['`fetch(...)`', 'return typeof fetch'],
    ['`require("fs")`', 'try { require("fs"); return "LOADED" } catch (e) { return e.name + ": " + e.message }'],
    ['`process.env`', 'try { return process.env } catch (e) { return e.name + ": " + e.message }'],
    ['`eval("1+1")`', 'try { return eval("1+1") } catch (e) { return e.name + ": " + e.message }'],
    ['`new Function(...)`', 'try { return new Function("return 1")() } catch (e) { return e.name + ": " + e.message }'],
    ['constructor escape via a tool function', 'try { return tools.uname.constructor.constructor("return process")() } catch (e) { return e.name + ": " + e.message }'],
    ['`import("fs")`', 'try { await import("fs"); return "IMPORTED" } catch (e) { return e.code || e.name }'],
    ['computed name `tools["s"+"h"]`', 'return await tools["s" + "h"](["-c", "id"])'],
    ['destructive `tools.slay`/`kill`', 'return await tools.kill(["-0", "1"])'],
    ['`find ... -delete`', 'return await tools.find(["/tmp", "-delete"])'],
    ['infinite loop (timeout 1500 ms)', 'while (true) {}', 1500],
    ['return 100,000 chars', 'return "x".repeat(100000)'],
  ];
  out('| Attempt | Outcome |');
  out('|---|---|');
  for (const [label, program, to] of probes) {
    const r = await runner.execute(program, to);
    const o = r.ok ? (r.truncated ? `truncated to ${r.value.length} chars with note` : `\`${JSON.stringify(r.value).slice(0, 90)}\``) : `\`${r.error.kind}${r.error.code ? '/' + r.error.code : ''}\` ${String(r.error.message).slice(0, 90)}`;
    out(`| ${label} | ${o.replace(/\|/g, '\\|')} |`);
  }
  out();
  out(`Sandbox network: ${state.policy.sandbox.network}.`);
  out();

  // ---------- Phase 4 + 6 ----------
  out('## Phase 4 — native checks through the gateway');
  out();
  await operator.post('/api/board/reset');
  const rep = (await runner.post('/api/checks/run', {})).json;
  out('| Check | Ran | Findings |');
  out('|---|---|---|');
  for (const c of rep.checks) out(`| ${c.check} | ${c.ok ? 'ok' : 'FAILED: ' + (c.error && c.error.message)} | ${c.finding_count} |`);
  out();
  out('| Severity | Finding | Receipt (seq) | Evidence excerpt |');
  out('|---|---|---|---|');
  for (const f of rep.findings) out(`| ${f.severity} | ${f.title.replace(/\|/g, '\\|')} | \`${f.evidence[0].receipt.slice(0, 12)}\` (#${f.evidence[0].seq}) | \`${f.evidence[0].excerpt.split('\n')[0].replace(/\s+/g, ' ').slice(0, 70).replace(/\|/g, '\\|')}\` |`);
  out();
  out(`Report signed (ed25519, key \`${rep.signature.key_id}\`); findings without a receipt in the chain: ${rep.rejected.length}.`);
  out();

  out('## Phase 6 — verification loop');
  out();
  await runner.post('/api/board/post', {});
  const real = rep.findings[0] ? rep.findings[0].evidence : [];
  await runner.post('/api/board/post', { tag: 'planted-false', findings: [
    { id: 'planted-false-listener-5555', severity: 'high', title: 'Listener on tcp/5555', evidence: real, reproduce: { tool: 'netstat', args: ['-an'], expect: { type: 'listener', proto: 'tcp', port: 5555 } } },
    { id: 'planted-false-process-ghostd', severity: 'medium', title: 'ghostd running', evidence: real, reproduce: { tool: 'ps', args: ['-A', '-o', 'pid=', '-o', 'comm='], expect: { type: 'process', name: 'ghostd' } } },
    { id: 'planted-false-forged-receipt', severity: 'high', title: 'cites a receipt that does not exist', evidence: [{ receipt: 'f'.repeat(64), tool: 'netstat', args: ['-an'], excerpt: '' }], reproduce: { tool: 'netstat', args: ['-an'], expect: { type: 'listener', proto: 'tcp', port: 4444 } } },
    { id: 'planted-false-needs-out-of-scope', severity: 'high', title: 'needs an out-of-scope host to prove', evidence: real, reproduce: { tool: 'ping', args: ['-c', '1', '203.0.113.9'], expect: { type: 'regex', pattern: '1 received' } } },
  ] });
  const verdicts = await workBoard({ url: base, token: tok('smith'), log: () => {} });
  out('Runner seat posts its findings plus planted false claims; Agent Smith\'s seat (separate token) reproduces each one itself:');
  out();
  out('| Claim | Verdict | Smith observed |');
  out('|---|---|---|');
  for (const v of verdicts) out(`| ${v.id} | **${v.verdict}** | ${String(v.observed).replace(/\|/g, '\\|').slice(0, 110)} |`);
  out();
  const vr = (await operator.post('/api/report/verified')).json;
  out(`Verified report: **${vr.findings.length} findings, all CONFIRMED**; excluded: ${vr.board.excluded.map((x) => `${x.id} (${x.status})`).join(', ') || 'none'}.`);
  out();

  // ---------- token surface ----------
  out('## Token surface (relative proxy)');
  out();
  const surface = JSON.stringify(tools);
  const cat = JSON.parse(fs.readFileSync(cfg.catalog, 'utf8'));
  const { Catalog } = require('../gateway/lib/catalog');
  const C = new Catalog(cat);
  const classicTools = C.visibleTools().map((x) => ({ name: x.name.replace(/[^A-Za-z0-9_-]/g, '_'), description: x.desc, inputSchema: { type: 'object', properties: { args: { type: 'array', items: { type: 'string' }, description: 'argv after the program name' }, timeout_ms: { type: 'integer' } } } }));
  const classicJson = JSON.stringify(classicTools);
  const tk = spawnSync('python3', ['-c', 'import sys,tiktoken,json;e=tiktoken.get_encoding("cl100k_base");print(json.dumps([len(e.encode(x)) for x in json.load(sys.stdin)]))'], { input: JSON.stringify([surface, classicJson]), encoding: 'utf8' });
  let counts = null; try { counts = JSON.parse(tk.stdout); } catch {}
  out('| Surface the model holds | Bytes | Tokens (cl100k_base proxy) |');
  out('|---|---|---|');
  out(`| Classic MCP: one tool per callable target utility (${classicTools.length} tools) | ${Buffer.byteLength(classicJson)} | ${counts ? counts[1] : 'n/a'} |`);
  out(`| Code Mode: \`search\` + \`execute\` | ${Buffer.byteLength(surface)} | ${counts ? counts[0] : 'n/a'} |`);
  out();
  out('cl100k_base is a relative proxy, not the billed count of any specific model; billed figures come from the provider\'s usage record. The classic row lists only the callable tools; listing every executable in the image would be larger.');
  out();
  const seal = (await operator.get('/api/seal')).json;
  out(`## Seal\n\nChain ${seal.chain_ok ? 'verified' : 'BROKEN'} at ${seal.entries} entries, head \`${seal.head}\`, ed25519 signature \`${seal.signature.sig.slice(0, 32)}…\` (key \`${seal.signature.key_id}\`). Verify cold: \`node gateway/cli.js verify-chain ${path.relative(process.cwd(), path.join(st, 'audit.log'))}\`.`);

  fs.mkdirSync(outDir, { recursive: true });
  const name = `${t.os === 'QNX' ? 'qnx' : 'standin'}-${date}`;
  fs.writeFileSync(path.join(outDir, `${name}.md`), md.join('\n') + '\n');
  fs.writeFileSync(path.join(outDir, `${name}.json`), JSON.stringify({ target: t, proof3, ladder: { status401: r401.status, tools: tools.map((x) => x.name) }, report: rep, verdicts, verified: vr, seal }, null, 2));
  console.error(`\nwrote ${path.join(outDir, name + '.md')}`);
  const pass = r401.status === 401 && tools.length === 2 && proof3.denied_spawned === 0 && proof3.denied_packets === 0 && proof3.allowed_spawned === 1 && (proof3.allowed_packets === null || proof3.allowed_packets > 0) && chain.ok && vr.findings.length > 0 && verdicts.filter((v) => v.id.startsWith('planted-false')).every((v) => v.verdict !== 'CONFIRMED');
  console.error(pass ? 'ALL DONE-TESTS PASS' : 'A DONE-TEST FAILED');
  process.exit(pass ? 0 : 1);
})().catch((e) => { console.error(e); process.exit(1); });
